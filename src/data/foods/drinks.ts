/**
 * Drinks by sugar level and size. Mamak and kopitiam words: o = no milk, c = evaporated milk,
 * plain = condensed milk; kosong = no sugar, kurang = about half. Besar or bungkus sizes are
 * separate entries so "teh tarik besar kurang" can pick both.
 */

const SWEETNESS_QUESTION = 'How sweet was it?';

/** Kosong / Kurang / Normal, in the order PortionChips shows them. */
function sweetness(kosong: Macros, kurang: Macros, normal: Macros): Variant[] {
  return [variant('Kosong', kosong), variant('Kurang', kurang), variant('Normal', normal)];
}

